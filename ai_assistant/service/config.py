"""Настройки сервиса. Читаются из переменных окружения с префиксом AIA_."""
import os
from dataclasses import dataclass


@dataclass(frozen=True)
class Config:
    grpc_port: int
    http_port: int
    stt_engine: str
    gigaam_model: str
    tts_engine: str
    tts_model: str
    vosk_tts_model_path: str
    tts_voice: str
    #: Библиотека заранее записанных голосов (tts.VoiceLibrary). Папки нет
    #: или она пуста — бот говорит движком синтеза, как раньше.
    voice_library_dir: str
    embedder_model: str
    similarity_threshold: float
    #: Индекс корпуса живых реплик (corpus_knn.py). Пусто или файла нет —
    #: бот решает только по формулировкам.
    corpus_index_path: str
    corpus_k: int
    corpus_threshold: float
    corpus_operator_threshold: float
    corpus_min_words: int
    silence_timeout_ms: int
    utterance_pause_ms: int
    stt_timeout_s: int
    knowledge_path: str
    feed_cache_path: str
    tts_cache_dir: str
    prewarm_tts: bool
    #: Куда складывать записи реплик, как их услышал движок распознавания.
    #: Пусто — не складывать вовсе (обычный режим).
    debug_audio_dir: str
    #: Как часто вхолостую прогонять распознавание и поиск, чтобы модели не
    #: выгружались из памяти во время простоя. 0 — не прогонять.
    keepwarm_seconds: int


def _env_str(name: str, default: str) -> str:
    return os.environ.get("AIA_" + name, default)


def _env_int(name: str, default: int) -> int:
    return int(os.environ.get("AIA_" + name, default))


def _env_bool(name: str, default: bool) -> bool:
    raw = os.environ.get("AIA_" + name)
    if raw is None:
        return default
    return raw.strip().lower() in ("1", "true", "yes", "on", "да")


def _env_float(name: str, default: float) -> float:
    return float(os.environ.get("AIA_" + name, default))


def load_config() -> Config:
    return Config(
        grpc_port=_env_int("GRPC_PORT", 50051),
        http_port=_env_int("HTTP_PORT", 8080),
        stt_engine=_env_str("STT_ENGINE", "vosk"),
        # v3_rnnt, а не v2_rnnt: замер 14.08.2026 на одном материале дал
        # распознавание 0.281 с против 0.378 с при том же результате.
        # Другие варианты: v3_ctc (ещё быстрее, чуть менее точна),
        # v3_e2e_rnnt (расставляет пунктуацию и заглавные буквы).
        gigaam_model=_env_str("GIGAAM_MODEL", "v3_rnnt"),
        # vosk, а не silero: модель Silero v5_ru лицензирована как CC BY-NC —
        # некоммерческая, — а бот работает на боевой линии коммерческой
        # компании (разбор лицензий 03.09.2026, UL-17568). Silero оставлен
        # запасным движком и включается этой же переменной.
        tts_engine=_env_str("TTS_ENGINE", "vosk"),
        # Только для silero. У vosk модель берётся из VOSK_TTS_MODEL_PATH.
        tts_model=_env_str("TTS_MODEL", "v4_ru"),
        # Папка с распакованной vosk-model-tts-ru-0.7-multi (~236 МБ). Пусто —
        # осознанно: библиотека умеет качать модель сама, но со станции GitHub
        # недоступен, поэтому путь задаётся явно и модель кладётся руками.
        vosk_tts_model_path=_env_str("VOSK_TTS_MODEL_PATH", ""),
        # s3 — диктор Vosk-TTS, выбранный 04.09.2026: лучшая разборчивость из
        # всех замеренных (49% против 44% у прежнего боевого голоса kseniya).
        tts_voice=_env_str("TTS_VOICE", "s3"),
        # Голоса операторов ОКК, склонированные CosyVoice 3 на видеокарте и
        # отобранные распознаванием (C:\aia_tts_lab\linux, 24.09.2026). В бою
        # видеокарта не нужна: фразы лежат готовыми файлами, а голос группы
        # линий выбирается в ERP тем же полем, что и дикторы Vosk.
        voice_library_dir=_env_str("VOICE_LIBRARY_DIR", "ai_assistant/voices"),
        embedder_model=_env_str("EMBEDDER_MODEL", "ai-forever/ru-en-RoSBERTa"),
        # 0.66 подобран замером 20.08.2026 на боевой базе из 40 направлений.
        # Посторонние вопросы (такси, погода, работа, аптека, «починить пиццу»)
        # — 0.472-0.643. Своё — 0.675-0.850, и нижний край держат короткие
        # запросы ремонта: «ремонт телевизора» 0.6752, «ремонт стиральной
        # машины» 0.6768. Порог стоит между ними, ближе к шуму: цена ошибки
        # несимметрична. Промах по своему вопросу стоит переспроса
        # (QUESTION_REASK_ATTEMPTS), а пролезший чужой — уверенного вопроса не
        # по делу и перевода в чужой отдел.
        #
        # Поставленные утром 0.68 продержались полдня: на живом звонке в 16:13
        # клиент сказал «ремонт стиральной машины» и не добрал трёх тысячных.
        # Утренний замер мерил развёрнутую речь («у меня стиралка перестала
        # отжимать» — 0.806) и этот класс фраз попросту не видел: в базе почти
        # все формулировки описывают поломку, а не просьбу о ремонте.
        #
        # Прежние 0.64 достались от замера 14.08.2026, когда база состояла из
        # 28 направлений без синонимов, и к 20.08 устарели: на живом звонке
        # "я не понимаю как мне починить пиццу" дало 0.6432 к формулировке
        # "почините посудомоечную машину" — и бот уверенно спросил клиента про
        # ремонт посудомойки. Обобщённые формулировки вида "почините X"
        # притягивают любое "починить что угодно": название техники в такой
        # фразе — малая часть смысла.
        #
        # Прежние 0.75 отсекали больше половины нормальной речи: реальное
        # "стиралка машинка сломалась" давало 0.719 и уходило на оператора
        # вместо уточняющего вопроса.
        #
        # Правило на будущее: чем больше синонимов в записях, тем выше можно
        # держать порог — варианты поднимают близость к своей записи, не трогая
        # близость к чужим. Но чем больше самих записей, тем теснее они стоят
        # друг к другу, и зазор снова сужается. После правки базы порог надо
        # перемерять, а не оставлять на глаз.
        similarity_threshold=_env_float("SIMILARITY_THRESHOLD", 0.66),
        # Корпус реплик из записей звонков (tools/build_corpus_index.py).
        # Если он уверен, его слово главнее формулировки. Порог здесь — доля
        # голосов соседей, а не близость, и подбирается отдельно от
        # SIMILARITY_THRESHOLD. 0.50 — замер 20.09.2026 по 5 фолдам на 14 670
        # живых репликах (measure_corpus.py --corpus-knn): «не туда» 6.6% при
        # ответе на 90% звонков; при 0.60 — 6.3%/87%, при 0.40 — 7.8%/93%.
        # Ниже порог — лучше, чем кажется: когда корпус не уверен, решение
        # уходит формулировкам, а те ошибаются чаще неуверенного корпуса.
        corpus_index_path=_env_str("CORPUS_INDEX_PATH", "ai_assistant/corpus_index.npz"),
        corpus_k=_env_int("CORPUS_K", 15),
        corpus_threshold=_env_float("CORPUS_THRESHOLD", 0.50),
        # Перевод на оператора без уточняющего вопроса — только при уверенной
        # победе: «вызвать мастера на дом» (0.70) и «я звонил по поводу
        # установки фильтра» (0.71) должны получить «что вас интересует?»,
        # а «человек обещал перезвонить» (1.00) — оператора (разбор второго
        # этапа теста 24.09.2026).
        # Замер на ручной тысяче 24.09.2026 (ответил / верно / новых заказов
        # ушло на оператора): без порога 98% / 87% / 17%; 0.65 — 92 / 87 / 7;
        # 0.72 — 89 / 87 / 6; 0.80 — 87 / 87 / 5. Точность не меняется, порог
        # торгует охват на лишние переводы; 0.72 ловит «вызвать мастера на дом»
        # (0.70) и почти не режет охват.
        corpus_operator_threshold=_env_float("CORPUS_OPERATOR_THRESHOLD", 0.72),
        # Реплики без содержания («угу здравствуйте», «установка») корпусу не
        # показываем: у них соседи — такие же пустые начала повторных звонков.
        corpus_min_words=_env_int("CORPUS_MIN_WORDS", 2),
        silence_timeout_ms=_env_int("SILENCE_TIMEOUT_MS", 15000),
        # 1500, а не 3000: с трёхсекундной паузой ответ бота приходит через ~4 секунды
        # после конца фразы, и разговор ощущается сломанным. Плата — бот перебьёт того,
        # кто задумался дольше полутора секунд.
        utterance_pause_ms=_env_int("UTTERANCE_PAUSE_MS", 1500),
        stt_timeout_s=_env_int("STT_TIMEOUT_S", 10),
        knowledge_path=_env_str("KNOWLEDGE_PATH", "ai_assistant/knowledge_base.json"),
        # Копия последней присланной посылки. Сервис поднимается с неё, не
        # дожидаясь робота: перезапуск занимает минуту, робот приходит раз в
        # десять.
        feed_cache_path=_env_str("FEED_CACHE_PATH", "ai_assistant/knowledge_feed_cache.json"),
        tts_cache_dir=_env_str("TTS_CACHE_DIR", "/tmp/aia_tts_cache"),
        # Синтезировать все известные фразы при старте, а не по ходу звонка.
        # Холодный синтез стоит до 2 секунд (замер 14.08.2026 на v5_ru), и
        # клиент слушает их как тишину. Старт удлиняется, звонки — нет.
        prewarm_tts=_env_bool("PREWARM_TTS", True),
        # По умолчанию пусто: это отладочный режим для разбора спорных
        # распознаваний, а не постоянное хранение записей разговоров.
        debug_audio_dir=_env_str("DEBUG_AUDIO_DIR", ""),
        # Пять минут — с запасом чаще, чем система успевает выгрузить страницы
        # простаивающего процесса, и достаточно редко, чтобы не мешать. Одна
        # прогонка стоит десятки миллисекунд.
        keepwarm_seconds=_env_int("KEEPWARM_SECONDS", 300),
    )
