-- ======================================================================
-- UL-17568. Уточняющий вопрос без рода.
--
-- Было: «Правильно я понял, что вас интересует ремонт стиральной машины?»
-- Стало: «Правильно понимаю, что вас интересует ремонт стиральной машины?»
--
-- Зачем: голос выбирается в справочнике и может быть женским (сейчас там
-- Ксения), а «понял» выдаёт мужчину. Форма без рода снимает вопрос навсегда:
-- при следующей смене голоса переписывать базу знаний не придётся.
--
-- Замена точечная, по подстроке — остальной текст вопроса у каждой темы свой
-- и не трогается. Скрипт идемпотентен: повторный запуск не найдёт что менять.
-- ======================================================================

SET DEFINE OFF

UPDATE ULTIMA.AI_KNOWLEDGE_BASE
   SET CLARIFYING_QUESTION = REPLACE(CLARIFYING_QUESTION, 'Правильно я понял,', 'Правильно понимаю,')
 WHERE CLARIFYING_QUESTION LIKE '%Правильно я понял,%';

COMMIT;


-- ----------------------------------------------------------------------
-- Проверка: в первой строке должен быть 0, во второй — 32.
-- ----------------------------------------------------------------------
SELECT COUNT(*) AS ОСТАЛОСЬ_С_РОДОМ
  FROM ULTIMA.AI_KNOWLEDGE_BASE
 WHERE CLARIFYING_QUESTION LIKE '%понял%';

SELECT COUNT(*) AS СТАЛО_БЕЗ_РОДА
  FROM ULTIMA.AI_KNOWLEDGE_BASE
 WHERE CLARIFYING_QUESTION LIKE '%Правильно понимаю,%';
