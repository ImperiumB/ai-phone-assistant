-- ======================================================================
-- UL-17568. «не» как вариант отрицательного ответа.
--
-- На живом звонке 18.08.2026 клиент так и ответил — «не». Распознавание
-- отработало точно, беда была в списке: там есть «не то», «не это»,
-- «не совсем», а голого «не» не было. Бот не понял внятный ответ и
-- предложил переформулировать вопрос.
--
-- Так говорят: «не» вместо «нет» — обычное разговорное сокращение, и
-- ждать от клиента полной формы нельзя.
--
-- Риск ложного срабатывания низкий: список применяется только в точке
-- подтверждения, где клиента уже спросили «да или нет», и только после
-- проверки положительных ответов. Фраза «да, не отжимает» уйдёт в согласие
-- по слову «да», не дойдя до этой строки.
--
-- Скрипт идемпотентен: повторный запуск ничего не добавит.
-- ======================================================================

SET DEFINE OFF

UPDATE ULTIMA.LINE_GROUPS
   SET AI_NEGATIVE_ANSWERS = AI_NEGATIVE_ANSWERS || CHR(10) || 'не'
 WHERE ID = 9060
   AND AI_NEGATIVE_ANSWERS IS NOT NULL
   AND CHR(10) || AI_NEGATIVE_ANSWERS || CHR(10) NOT LIKE '%' || CHR(10) || 'не' || CHR(10) || '%';

COMMIT;


-- ----------------------------------------------------------------------
-- Проверка: вариантов должно стать 16, среди них строка «не».
-- ----------------------------------------------------------------------
SELECT LENGTH(AI_NEGATIVE_ANSWERS) - LENGTH(REPLACE(AI_NEGATIVE_ANSWERS, CHR(10))) + 1 AS ВАРИАНТОВ
  FROM ULTIMA.LINE_GROUPS WHERE ID = 9060;
