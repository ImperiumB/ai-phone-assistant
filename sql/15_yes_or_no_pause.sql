-- Проверка: какая пунктуация стоит сейчас.
SELECT COUNT(*) AS ВСЕГО,
       SUM(CASE WHEN CLARIFYING_QUESTION LIKE '%да, или нет%' THEN 1 ELSE 0 END) AS ЗАПЯТАЯ,
       SUM(CASE WHEN CLARIFYING_QUESTION LIKE '%да... или нет%' THEN 1 ELSE 0 END) AS МНОГОТОЧИЕ,
       SUM(CASE WHEN CLARIFYING_QUESTION LIKE '%пожалуйста, да или нет%' THEN 1 ELSE 0 END) AS БЕЗ_ПАУЗЫ
  FROM ULTIMA.AI_KNOWLEDGE_BASE
 WHERE CLARIFYING_QUESTION IS NOT NULL;

SELECT ID, AI_CONFIRM_NOT_HEARD FROM ULTIMA.LINE_GROUPS
 WHERE AI_CONFIRM_NOT_HEARD IS NOT NULL;
