-- ======================================================================
-- UL-17568. Пауза перед «или» в вопросах «да или нет».
--
-- Файл в UTF-8 без BOM. Запускать с NLS_LANG=RUSSIAN_CIS.AL32UTF8,
-- иначе кириллица приедет в справочник мусором.
--
-- ЗАЧЕМ
--   Заказчик слушал образцы 03.09.2026 и опознал бота мгновенно по одному
--   месту: «Ответьте, пожалуйста, да или нет». Это перечисление в конце
--   вопроса, и ему нужна своя интонация — подъём на «да», падение на «нет».
--   Все модели синтеза заваливают её одинаково: вопросительную интонацию они
--   тратят на основной вопрос, а хвост дочитывают ровным голосом.
--
--   Дело не в модели, а в тексте: знак препинания перед «или» заставляет
--   синтез сделать паузу.
--
-- ВНИМАНИЕ: ЗНАК ЗАВИСИТ ОТ МОДЕЛИ СИНТЕЗА
--   Пунктуацию подбирали на слух, и модели слышат её по-разному:
--
--     Silero (v5_ru и MIT-линейка) — ЗАПЯТАЯ: «да, или нет»
--                                    многоточие у него звучит нарочито;
--     Vosk-TTS                     — МНОГОТОЧИЕ: «да... или нет»
--                                    запятую он проглатывает, паузы нет вовсе.
--
--   Поэтому ниже ДВА блока. Выполнить надо ТОТ, что соответствует модели,
--   которая стоит в бою. Сейчас это Silero — раскомментирован блок «А».
--   При переходе на воск выполнить блок «Б»: он переведёт тексты обратно.
--
-- ЧТО МЕНЯЕТСЯ
--   уточняющие вопросы базы знаний (на 03.09.2026 их 40, хвост у всех)
--   и фраза группы линий «при неразборчивом ответе» — там та же
--   конструкция, но со «Скажите».
--
--   Темы не создаются и не удаляются, меняется только текст.
--
-- ИДЕМПОТЕНТЕН: замена идёт только там, где стоит прежний текст.
-- ======================================================================

SET DEFINE OFF;

-- ----------------------------------------------------------------------
-- БЛОК А. Для Silero — запятая. ВЫПОЛНЯЕТСЯ.
-- ----------------------------------------------------------------------
UPDATE ULTIMA.AI_KNOWLEDGE_BASE
   SET CLARIFYING_QUESTION = REPLACE(CLARIFYING_QUESTION,
                                     'Ответьте, пожалуйста, да или нет',
                                     'Ответьте, пожалуйста: да, или нет')
 WHERE CLARIFYING_QUESTION LIKE '%Ответьте, пожалуйста, да или нет%';

UPDATE ULTIMA.LINE_GROUPS
   SET AI_CONFIRM_NOT_HEARD = REPLACE(AI_CONFIRM_NOT_HEARD,
                                      'Скажите, пожалуйста, да или нет',
                                      'Скажите, пожалуйста: да, или нет')
 WHERE AI_CONFIRM_NOT_HEARD LIKE '%Скажите, пожалуйста, да или нет%';

-- ----------------------------------------------------------------------
-- БЛОК Б. Для Vosk-TTS — многоточие. ВЫПОЛНЯТЬ ТОЛЬКО ПРИ ПЕРЕХОДЕ НА ВОСК.
