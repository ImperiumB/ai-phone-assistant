-- ======================================================================
-- UL-19020. Откат части sql/20: формы «у меня вопрос по <тема>» вредны.
--
-- 14.10.2026, звонок 1791965278: «здравствуйте, вопрос по заказу» — корпус
-- уверенно (1.0) ведёт на сопровождение, но свежая формулировка клининга
-- «у меня вопрос по заказ клининговых услуг» дала близость 0.75 и перебила
-- корпус: бот спросил про уборку. Слова «вопрос по» в начале — признак
-- повторного обращения, в формулировках новых заказов им не место.
--
-- Удаляются только строки, добавленные sql/20 (ID > 834) и начинающиеся
-- с «у меня вопрос по ». Файл в UTF-8 без BOM.
-- ======================================================================

SET DEFINE OFF;

DELETE FROM ULTIMA.AI_KB_PHRASES
 WHERE ID > 834
   AND LOWER(TRIM(PHRASE)) LIKE 'у меня вопрос по %';

COMMIT;

