-- UL-19020. Убрать жаргон из фраз бота (заказчик, 22.10.2026): «дератизация»
-- (запись грызунов 139) и «дезинсекция»/«дезинфекция» (насекомые 24) — и в
-- уточняющем вопросе, и во фразе перевода. Клиенту эти слова не нужны (он
-- говорит «крысы/мыши», «тараканы/клопы»), а синтез на них спотыкается.
-- Ключевые фразы записей не трогаем — на попадание эти слова не влияли.
-- Файл в UTF-8 без BOM.
-- ======================================================================
SET DEFINE OFF;

UPDATE ULTIMA.AI_KNOWLEDGE_BASE
   SET CLARIFYING_QUESTION = 'Правильно понимаю, что вас интересует обработка от грызунов?',
       POSITIVE_REPLY      = 'Соединяю вас со специалистом по обработке от грызунов, оставайтесь на линии'
 WHERE ID = 139;

UPDATE ULTIMA.AI_KNOWLEDGE_BASE
   SET CLARIFYING_QUESTION = 'Правильно понимаю, что вас интересует обработка от насекомых?',
       POSITIVE_REPLY      = 'Соединяю вас со специалистом по обработке от насекомых, оставайтесь на линии'
 WHERE ID = 24;

COMMIT;

SELECT ID, CLARIFYING_QUESTION, POSITIVE_REPLY FROM ULTIMA.AI_KNOWLEDGE_BASE WHERE ID IN (24, 139) ORDER BY ID;
