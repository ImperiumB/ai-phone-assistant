-- ULTIMA.AI_KNOWLEDGE_BASE_SEQ не двигалась ни разу, а в таблице уже 178 строк с
-- плотными кодами 1..178.
--
-- Обработчик теперь создаёт запись штатным путём, то есть берёт код из этой
-- последовательности (DefaultDictionaryManager: db.GetNewID(tableName + "_SEQ")).
-- Если последовательность не сдвинуть, первый же вызов вернёт 1 и упадёт с
-- ORA-00001, а каждая повторная попытка сожжёт ещё один номер. То же случилось бы
-- и при создании записи аналитиком из формы.
--
-- ПОРЯДОК: выполнять ПОСЛЕ заливки обработчика 15422, но ДО того, как аналитик
-- сядет за форму и до первого неопознанного вопроса на линии бота.
--
-- Последовательность нам не видна на чтение (проба CURRVAL даёт ORA-01031, нет
-- привилегии), поэтому сдвиг делается вслепую, но безопасно: сначала смотрим, где
-- она стоит, потом добираем разницу.

-- ШАГ 1. Узнать, где последовательность стоит сейчас.
-- Внимание: NEXTVAL сам сдвигает её на единицу, это нормально.
SELECT ULTIMA.AI_KNOWLEDGE_BASE_SEQ.NEXTVAL AS "ТЕКУЩИЙ КОД" FROM DUAL;

-- ШАГ 2. Если в шаге 1 вернулось число БОЛЬШЕ 178, последовательность уже сдвинута
-- кем-то раньше: ничего больше делать не надо, перейти к шагу 4.
--
-- Если вернулось число МЕНЬШЕ ИЛИ РАВНОЕ 178 (ожидаем 1), добрать разницу. Ниже
-- расчёт для самого частого случая, когда шаг 1 вернул 1: добираем до 179, то есть
-- на 178 вперёд. Если шаг 1 вернул другое число N, в INCREMENT BY подставить
-- (179 - N).
ALTER SEQUENCE ULTIMA.AI_KNOWLEDGE_BASE_SEQ INCREMENT BY 178;

SELECT ULTIMA.AI_KNOWLEDGE_BASE_SEQ.NEXTVAL AS "ДОЛЖНО СТАТЬ 179" FROM DUAL;

ALTER SEQUENCE ULTIMA.AI_KNOWLEDGE_BASE_SEQ INCREMENT BY 1;

-- ШАГ 3. Проверка: следующий код должен быть 180, то есть больше MAX(ID).
SELECT ULTIMA.AI_KNOWLEDGE_BASE_SEQ.NEXTVAL AS "СЛЕДУЮЩИЙ КОД" FROM DUAL;

-- ШАГ 4. Контроль: максимум в таблице должен быть меньше того, что отдаёт
-- последовательность. Если это не так, НЕ ДАВАТЬ аналитику заводить записи.
SELECT MAX(ID) AS "МАКСИМУМ В ТАБЛИЦЕ", '178 на 09.11.2026' AS "БЫЛО"
  FROM ULTIMA.AI_KNOWLEDGE_BASE;

