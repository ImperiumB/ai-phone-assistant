-- ШАГ 4. ОБЯЗАТЕЛЬНО, если аналитик будет добавлять формулировки из формы.
--
-- Та же мина, что чинил sql/35, только на второй таблице. Все формулировки
-- 1..1026 вставлены скриптами с явными кодами, то есть последовательность
-- ULTIMA.AI_KB_PHRASES_SEQ не двигалась ни разу и стоит на единице. Первая
-- формулировка, добавленная из справочника «Формулировки базы знаний» (56447),
-- возьмёт код оттуда и упадёт с ORA-00001, а каждая повторная попытка сожжёт ещё
-- один номер.
--
-- Блок делает всё сам и БЕЗОПАСЕН ПРИ ПОВТОРНОМ ЗАПУСКЕ. Руками шаг инкремента
-- трогать не надо.
--
-- Почему блоком, а не тремя ALTER подряд, как в sql/35: шаг инкремента это
-- ПОСТОЯННОЕ свойство последовательности, а не одноразовое. В прежней версии
-- условие «если последовательность уже впереди, ничего не делай» стояло
-- КОММЕНТАРИЕМ, то есть при выполнении файла целиком ALTER срабатывал
-- безусловно, а завершающий «INCREMENT BY 1» можно было не доехать. Так 09.11
-- и вышло: последовательность осталась с шагом 1026 и прыгала на 1026 вперёд
-- при каждом обращении. Лечилось одной строкой, но ловушку надо убрать.
SET SERVEROUTPUT ON
DECLARE
    v_max  NUMBER;
    v_next NUMBER;
BEGIN
    SELECT NVL(MAX(ID), 0) INTO v_max FROM ULTIMA.AI_KB_PHRASES;
    -- Шаг возвращаем в единицу ПЕРВЫМ делом: если его оставили сломанным
    -- прошлым запуском, это само по себе и есть починка.
    EXECUTE IMMEDIATE 'ALTER SEQUENCE ULTIMA.AI_KB_PHRASES_SEQ INCREMENT BY 1';
    SELECT ULTIMA.AI_KB_PHRASES_SEQ.NEXTVAL INTO v_next FROM DUAL;
    IF v_next <= v_max THEN
        EXECUTE IMMEDIATE 'ALTER SEQUENCE ULTIMA.AI_KB_PHRASES_SEQ INCREMENT BY '
                          || TO_CHAR(v_max + 1 - v_next);
        SELECT ULTIMA.AI_KB_PHRASES_SEQ.NEXTVAL INTO v_next FROM DUAL;
        EXECUTE IMMEDIATE 'ALTER SEQUENCE ULTIMA.AI_KB_PHRASES_SEQ INCREMENT BY 1';
        DBMS_OUTPUT.PUT_LINE('Последовательность догнали. MAX(ID) = ' || v_max
                             || ', следующий код будет ' || TO_CHAR(v_next + 1));
    ELSE
        DBMS_OUTPUT.PUT_LINE('Последовательность уже впереди таблицы. MAX(ID) = ' || v_max
                             || ', следующий код будет ' || TO_CHAR(v_next + 1));
    END IF;
END;
/
