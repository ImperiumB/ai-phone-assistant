-- ЧТО ИЗ ЗАГОТОВОК ОКАЗАЛОСЬ ЦЕННЫМ: их ВОПРОСИТЕЛЬНАЯ ФОРМА. Замер показал
-- перекос внутри записи 10: у утюга три вопросительные формы плюс две других, и
-- реплика «вопрос такой вы ремонтируете утюги» берётся с близостью 0,818. У
