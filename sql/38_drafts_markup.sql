-- ПОЧЕМУ НАБОР ИМЕННО ТАКОЙ. Первая проба ставила по ОДНОЙ вопросительной форме
-- на прибор и дала ноль изменений, но показала причину: та же реплика сдвинулась
-- 0,7017 -> 0,7377 и не дотянула до порога на 0,0023. Разницу съедает вежливость
-- в начале реплики («добрый день девушка извините пожалуйста»): у утюга похожая
-- реплика короче, отсюда его 0,818. Поэтому набор повторяет ВСЮ парадигму утюга
-- (три вопросительные формы плюс «ремонт <приборов>»), а не одну форму. Это
-- тиражирование правила, а не подгонка под реплику замера.
--
-- ЧЕГО ЭТА ПРАВКА НЕ ЧИНИТ, и это честно проверено:
--   [343]  «проконсультироваться по работе аэрогриля»    0,6951 без изменений
--   [2031] «блендер сломался сколько стоит диагностика»  0,6673 без изменений
--   [2200] «браун миксер не миксер как же он называется» 0,7147 -> 0,7197
-- Первые две это не заявка на ремонт, а консультация и вопрос цены, им на
