-- Это правило С7 в чистом виде. Шаг 2 ниже достраивает парадигму утюга для
-- остальных приборов, тексты намыты из корпуса живых реплик, не придуманы.
--
-- РЕЗУЛЬТАТ ЗАМЕРА ШАГА 2 (линейка, 4000 размеченных реплик, отсчёт на посылке
-- от 16:40 с ветеринарной правкой):
--   вердикт направления: РАЗОШЁЛСЯ на 1 реплике из 4000, и разошёлся К ЛУЧШЕМУ:
--     «молчит» стало «верно (сценарий)»;
--   метрика С1: 1 смена из 851, в корзинах «вопрос появился» и «сменился ответ
--     на согласие». Это та же реплика: бот прежде на ней сдавался молча, а
--     теперь задаёт вопрос про мелкую бытовую технику.
--   побочных смен ноль: остальные 3999 реплик совпали по всем столбцам.
--
--   [3847] «добрый день девушка извините пожалуйста а вы блендеры ремонтируете»
--          близость 0,7017 -> 0,7633 при пороге 0,74, вердикт молчит -> верно.
