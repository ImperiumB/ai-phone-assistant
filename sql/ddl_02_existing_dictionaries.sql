-- =====================================================================
-- UL-17568 / UL-18797. Виртуальный AI-помощник.
-- DDL для правок в СУЩЕСТВУЮЩИЕ справочники.
-- Новые справочники (AI_SCENARIOS, AI_KNOWLEDGE_BASE, AI_KB_PHRASES)
-- уже заведены отдельно.
--
-- Типы взяты один в один с соседними колонками боевого астербота:
--   строки  -> VARCHAR2(256)   (как BYE_CHECK_UP, VOICE, GREETINGS_PATH)
--   галки   -> NUMBER(1,0) DEFAULT 0  (как IS_USE_REC_AUDIO)
-- Списки ответов шире: тридцать три формулировки, по одной на строку,
-- в 256 не помещаются.
--
-- Кодировка базы CL8MSWIN1251 (однобайтовая), поэтому 256 = 256 русских
-- букв, а не 85. Пересчитывать длины не нужно.
--
-- Существующие строки: колонки добавляются NULLABLE с DEFAULT 0,
-- поэтому старые записи читаются как 0. Досыпать UPDATE не требуется.
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. LINE_PHONES - галка "Виртуальный AI помощник"
--
-- Пункт 1 ТЗ: звонки на такой номер обрабатывает бот и не распределяются
-- на операторов КЦ по диалплану. Редактирование закрыто КТ 27013.
-- ---------------------------------------------------------------------
ALTER TABLE ULTIMA.LINE_PHONES ADD (
  IS_AI_ASSISTANT   NUMBER(1,0)   DEFAULT 0
);


-- ---------------------------------------------------------------------
-- 2. LINE_GROUPS - настройки виртуального AI-помощника
--
-- Отдельный блок от настроек боевого астербота: у них разные сценарии
-- и разные фразы, смешивать нельзя.
-- ---------------------------------------------------------------------
ALTER TABLE ULTIMA.LINE_GROUPS ADD (
  -- голос синтеза (Silero: eugene, xenia, baya, kseniya, aidar)
  AI_VOICE                  VARCHAR2(256),

  -- приветствие
  AI_GREETING               VARCHAR2(256),
  AI_GREETING_PATH          VARCHAR2(256),

  -- не расслышали клиента, просим повторить
  AI_MISRECOGNITION         VARCHAR2(256),
  AI_MISRECOGNITION_PATH    VARCHAR2(256),

  -- переводим на оператора
  AI_TRANSFER_PHRASE        VARCHAR2(256),
  AI_TRANSFER_PHRASE_PATH   VARCHAR2(256),

  -- клиент молчит
  AI_SILENCE_PHRASE         VARCHAR2(256),
  AI_SILENCE_PHRASE_PATH    VARCHAR2(256),

  -- клиент ответил "нет" на уточняющий вопрос: расслышали, но не угадали
  -- тему. Просить переформулировать в этом случае невежливо.
  AI_WRONG_GUESS_PHRASE     VARCHAR2(256),
  AI_WRONG_GUESS_PATH       VARCHAR2(256),

  -- играть заранее записанные аудиофайлы вместо синтеза
  IS_USE_REC_AUDIO_AI       NUMBER(1,0)    DEFAULT 0,

  -- ответы на уточняющий вопрос, по одной формулировке на строку.
  -- Общие для всех записей базы знаний: это свойство ответа, а не темы.
  AI_POSITIVE_ANSWERS       VARCHAR2(1000),
  AI_NEGATIVE_ANSWERS       VARCHAR2(1000)
);

COMMIT;


-- ---------------------------------------------------------------------
-- Проверка: должно вернуться 15 строк (1 + 14)
-- ---------------------------------------------------------------------
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_LENGTH, DATA_DEFAULT
  FROM ALL_TAB_COLUMNS
 WHERE OWNER = 'ULTIMA'
   AND TABLE_NAME IN ('LINE_PHONES', 'LINE_GROUPS')
   AND (COLUMN_NAME LIKE 'AI\_%' ESCAPE '\'
        OR COLUMN_NAME IN ('IS_AI_ASSISTANT', 'IS_USE_REC_AUDIO_AI'))
 ORDER BY TABLE_NAME, COLUMN_NAME;
