def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--feed", default=os.path.join(REPO, "ai_assistant", "knowledge_feed_cache.json"))
    args = ap.parse_args()
    cfg = load_config()
    embedder = SentenceTransformerEmbedder(cfg.embedder_model)
    corpus = load_corpus_index(cfg)
    feed = parse_feed(json.load(io.open(args.feed, encoding="utf-8")))
    knowledge = KnowledgeBase(feed.records, embedder, cfg.similarity_threshold, corpus=corpus)
    factory = build_dialog_factory(support_exten="7082", sales_exten="7082")
    engine = factory(knowledge, feed)

    clock = {"now": 1000.0}
    dialog_module._now = lambda: clock["now"]

    passed = 0
    for n, (name, steps, (kind, piece)) in enumerate(CASES):
        linked = "regress-%d" % n
        engine.handle({"linkedId": linked, "recognizedText": "", "silenceDetected": "False"})
        result = {}
        for step in steps:
            point, text = step[0], step[1]
            clock["now"] += step[2] if len(step) > 2 else 10.0
            prms = engine.handle({"linkedId": linked, "conversationPoint": point, "recognizedText": text, "silenceDetected": "False"})
            result = {p["Key"]: p["Value"] for p in prms}
        action, said = result.get("Action", ""), (result.get("TextToSpeak") or "")
        low = said.lower()
        if kind == "ask":
            ok = action == "Recognize" and low.startswith("правильно") and piece in low
        elif kind == "not-ask":
            ok = not (low.startswith("правильно") and piece in low)
        elif kind == "redirect":
            ok = action == "Redirect" and piece in low
        elif kind == "redirect-equipment":
            ok = action == "Redirect" and piece in (result.get("EquipmentType") or "").lower()
        elif kind == "not-redirect":
            ok = action != "Redirect"
        elif kind == "reask":
            ok = action == "Recognize" and not low.startswith("правильно") and piece in low
        elif kind == "listen":
            ok = action == "Recognize" and said == ""
        else:
            ok = True
        passed += ok
        print("%s  %-52s | %-9s %s%s" % ("OK " if ok else "FAIL", name[:52], action, said[:80],
                                        (" [" + result["EquipmentType"] + "]") if result.get("EquipmentType") else ""))
    print("\nпрошло %d из %d" % (passed, len(CASES)))


if __name__ == "__main__":
    main()
